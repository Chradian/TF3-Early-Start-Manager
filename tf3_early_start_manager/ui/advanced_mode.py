from PySide6.QtCore import Qt
from PySide6.QtWidgets import QCheckBox,QFrame,QGridLayout,QHBoxLayout,QHeaderView,QLabel,QLineEdit,QPushButton,QSpinBox,QSplitter,QTableView,QTextEdit,QTreeWidget,QVBoxLayout,QWidget
from .resource_browser import ResourceFilterProxyModel,ResourceTableModel
TARGET_YEAR=1850

class AdvancedModeBuilder:
    def __init__(self,host): object.__setattr__(self,"host",host)
    def __getattr__(self,n): return getattr(self.host,n)
    def __setattr__(self,n,v): setattr(self.host,n,v) if n!="host" else object.__setattr__(self,n,v)

    def _advanced_page(self) -> QWidget:
        page = QWidget()
        lay = QVBoxLayout(page)
        lay.setContentsMargins(0, 0, 0, 0)

        toolbar = QFrame()
        toolbar.setObjectName("panel")
        tr = QHBoxLayout(toolbar)
        scan = QPushButton(self.tr("actions.scan_content"))
        scan.setObjectName("primary")
        scan.clicked.connect(self.scan_content)
        self.source_status = QLabel(self.tr("status.checking_content"))
        self.source_status.setObjectName("sourceStatus")
        self.source_status.setToolTip(
            self.tr("tooltips.source_status")
        )
        self.force_rescan = QCheckBox(self.tr("filters.force_rescan"))
        self.search = QLineEdit()
        self.search.setPlaceholderText(self.tr("placeholders.search_resources"))
        self.search.textChanged.connect(self.apply_resource_filter)
        self.transitions_only = QCheckBox(self.tr("filters.original_1850_1900"))
        self.transitions_only.toggled.connect(self.apply_resource_filter)
        self.changed_only = QCheckBox(self.tr("filters.only_changes"))
        self.changed_only.toggled.connect(self.apply_resource_filter)
        self.source_all = QCheckBox(self.tr("sources.all"))
        self.source_all.setChecked(True)
        self.source_all.toggled.connect(self.toggle_all_sources)
        self.source_vanilla = QCheckBox(self.tr("sources.vanilla"))
        self.source_modio = QCheckBox(self.tr("sources.modio"))
        self.source_local = QCheckBox(self.tr("sources.local"))
        for checkbox in (self.source_vanilla, self.source_modio, self.source_local):
            checkbox.setChecked(True)
            checkbox.toggled.connect(self.apply_resource_filter)
        scan_block = QVBoxLayout()
        scan_block.setContentsMargins(0, 0, 0, 0)
        scan_block.setSpacing(4)
        scan_block.setSizeConstraint(QVBoxLayout.SizeConstraint.SetMinimumSize)
        scan_top = QHBoxLayout()
        scan_top.setContentsMargins(0, 0, 0, 0)
        scan_top.setSpacing(8)
        scan_top.addWidget(scan)
        scan_top.addWidget(self.source_status)
        scan_top.addStretch()
        scan_block.addLayout(scan_top)
        scan_block.addWidget(self.force_rescan)
        # Two-row toolbar: scan controls keep the left column; search/filters align
        # with the resource table that starts to the right of the tree panel.
        tr.setContentsMargins(8, 8, 8, 8)
        tr.setSpacing(8)
        scan_wrapper = QWidget()
        scan_wrapper.setLayout(scan_block)
        tr.addWidget(scan_wrapper)

        filter_block = QVBoxLayout()
        filter_block.setContentsMargins(0, 0, 0, 0)
        filter_block.setSpacing(6)
        filter_block.addWidget(self.search)

        filters_row = QHBoxLayout()
        filters_row.setContentsMargins(0, 0, 0, 0)
        filters_row.setSpacing(8)
        filters_row.addWidget(QLabel(self.tr("sections.sources")))
        filters_row.addWidget(self.source_all)
        filters_row.addWidget(self.source_vanilla)
        filters_row.addWidget(self.source_modio)
        filters_row.addWidget(self.source_local)
        filters_row.addWidget(self.transitions_only)
        filters_row.addWidget(self.changed_only)
        filters_row.addStretch(1)
        filter_block.addLayout(filters_row)

        content_grid = QGridLayout()
        content_grid.setContentsMargins(8, 8, 8, 8)
        content_grid.setHorizontalSpacing(4)
        content_grid.setVerticalSpacing(6)
        lay.addLayout(content_grid, 1)
        tree_panel = QWidget()
        tree_layout = QVBoxLayout(tree_panel)
        tree_layout.setContentsMargins(0, 0, 0, 0)
        tree_header = QHBoxLayout()
        tree_title = QLabel(self.tr("sections.resources"))
        tree_title.setObjectName("section")
        self.tree_toggle_button = QPushButton(self.tr("actions.expand_all"))
        self.tree_toggle_button.setToolTip(self.tr("tooltips.expand_all_resources"))
        self.tree_toggle_button.clicked.connect(self.toggle_resource_tree_expansion)
        tree_header.addWidget(tree_title)
        tree_header.addStretch()
        tree_header.addWidget(self.tree_toggle_button)
        tree_layout.addLayout(tree_header)
        self.show_all_resources = QCheckBox(self.tr("filters.show_all"))
        self.show_all_resources.setChecked(
            str(self.settings.value("show_all_resources", "false")).lower() == "true"
        )
        self.show_all_resources.setToolTip(
            self.tr("tooltips.show_all_resources")
        )
        self.show_all_resources.toggled.connect(self._show_all_resources_changed)
        tree_layout.addWidget(self.show_all_resources)
        self.resource_tree = QTreeWidget()
        self.resource_tree.setHeaderHidden(True)
        self.resource_tree.setMinimumWidth(220)
        self.resource_tree.itemSelectionChanged.connect(self.apply_resource_filter)
        tree_layout.addWidget(self.resource_tree, 1)
        content_grid.addWidget(scan_wrapper, 0, 0)
        content_grid.addLayout(filter_block, 0, 1)
        content_grid.addWidget(tree_panel, 1, 0)

        right = QWidget()
        rl = QVBoxLayout(right)
        rl.setContentsMargins(0, 0, 0, 0)
        self.resource_model = ResourceTableModel(self.tr, self.host)
        self.resource_proxy = ResourceFilterProxyModel(self.host)
        self.resource_proxy.setSourceModel(self.resource_model)
        self.resource_table = QTableView()
        self.resource_table.setModel(self.resource_proxy)
        self.resource_table.setAlternatingRowColors(True)
        self.resource_table.setSelectionBehavior(QTableView.SelectionBehavior.SelectRows)
        self.resource_table.setSelectionMode(QTableView.SelectionMode.ExtendedSelection)
        self.resource_table.setSortingEnabled(True)
        self.resource_table.sortByColumn(1, Qt.SortOrder.AscendingOrder)
        self.resource_table.setMouseTracking(True)
        self.resource_table.setContextMenuPolicy(Qt.ContextMenuPolicy.CustomContextMenu)
        self.resource_table.customContextMenuRequested.connect(self.open_resource_context_menu)
        self.resource_table.entered.connect(self.update_resource_preview)
        self.resource_table.selectionModel().selectionChanged.connect(lambda *_: self.update_resource_count())
        self.resource_table.selectionModel().currentChanged.connect(
            lambda current, _previous: self.update_resource_preview(current) if current.isValid() else None
        )
        hdr = self.resource_table.horizontalHeader()
        hdr.setSectionResizeMode(QHeaderView.ResizeMode.Interactive)
        hdr.resizeSection(0, 60)
        hdr.resizeSection(1, 390)
        hdr.resizeSection(2, 300)
        hdr.resizeSection(3, 100)
        hdr.resizeSection(4, 105)
        hdr.resizeSection(5, 105)
        hdr.resizeSection(6, 105)
        hdr.resizeSection(7, 105)
        hdr.setStretchLastSection(False)
        rl.addWidget(self.resource_table, 1)

        self.preview_panel = QFrame()
        self.preview_panel.setObjectName("panel")
        preview_layout = QHBoxLayout(self.preview_panel)
        preview_layout.setContentsMargins(12, 8, 12, 8)
        self.preview_image = QLabel(self.tr("preview.no_preview"))
        self.preview_image.setFixedSize(240, 135)
        self.preview_image.setAlignment(Qt.AlignmentFlag.AlignCenter)
        self.preview_image.setStyleSheet("background:#15181c;border:1px solid #363b44;")
        self.preview_text = QLabel(self.tr("preview.hover_hint"))
        self.preview_text.setWordWrap(True)
        self.preview_description = QTextEdit()
        self.preview_description.setReadOnly(True)
        self.preview_description.setPlaceholderText(self.tr("placeholders.mod_description"))
        self.preview_description.setMinimumWidth(320)
        self.preview_description.setMaximumHeight(150)
        preview_layout.addWidget(self.preview_image)
        preview_layout.addWidget(self.preview_text, 1)
        preview_layout.addWidget(self.preview_description, 1)
        rl.addWidget(self.preview_panel)

        bottom = QFrame()
        bottom.setObjectName("panel")
        bottom_layout = QVBoxLayout(bottom)
        br = QHBoxLayout()
        action_row = QHBoxLayout()
        bottom_layout.addLayout(br)
        bottom_layout.addLayout(action_row)
        self.change_from = QCheckBox(self.tr("timeline.from"))
        self.change_from.setChecked(True)
        self.year_spin = QSpinBox()
        self.year_spin.setRange(TARGET_YEAR, 9999)
        self.year_spin.setValue(1850)
        self.change_to = QCheckBox(self.tr("timeline.until"))
        self.until_spin = QSpinBox()
        self.until_spin.setRange(0, 9999)
        self.until_spin.setSpecialValueText("∞")
        self.until_spin.setValue(0)
        set_year = QPushButton(self.tr("actions.apply_selected"))
        set_year.clicked.connect(self.set_selected_year)
        reset = QPushButton(self.tr("actions.reset_selected"))
        reset.clicked.connect(self.reset_selected)
        start_game = QPushButton(self.tr("game.start"))
        start_game.clicked.connect(self.start_game)
        install = QPushButton(self.tr("actions.install_update_compatibility"))
        install.setToolTip(
            self.tr("tooltips.install_update_compatibility")
        )
        install.clicked.connect(self.install_current_overrides)
        self.advanced_update_compat_button = install
        self.resource_count = QLabel(self.tr("status.resources_count", count=0))
        br.addWidget(self.change_from)
        br.addWidget(self.year_spin)
        br.addWidget(self.change_to)
        br.addWidget(self.until_spin)
        br.addWidget(set_year)
        br.addWidget(reset)
        br.addStretch()
        br.addWidget(self.resource_count)
        action_row.addWidget(install)
        action_row.addStretch(1)
        action_row.addWidget(start_game)
        rl.addWidget(bottom)
        content_grid.addWidget(right, 1, 1)
        content_grid.setColumnMinimumWidth(0, 250)
        content_grid.setColumnStretch(0, 0)
        content_grid.setColumnStretch(1, 1)
        content_grid.setRowStretch(0, 0)
        content_grid.setRowStretch(1, 1)
        self._build_resource_tree()
        return page
