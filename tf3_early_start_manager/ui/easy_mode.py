from PySide6.QtWidgets import QFrame,QHBoxLayout,QLabel,QPushButton,QVBoxLayout,QWidget

class EasyModeBuilder:
    def __init__(self,host): object.__setattr__(self,"host",host)
    def __getattr__(self,n): return getattr(self.host,n)
    def __setattr__(self,n,v): setattr(self.host,n,v) if n!="host" else object.__setattr__(self,n,v)

    def _easy_page(self) -> QWidget:
        page = QWidget()
        lay = QVBoxLayout(page)
        lay.setContentsMargins(0, 0, 0, 0)
        status = QFrame()
        status.setObjectName("panel")
        sl = QVBoxLayout(status)
        heading = QLabel(self.tr("sections.early_start"))
        heading.setObjectName("section")
        sl.addWidget(heading)
        self.easy_game = QLabel()
        self.easy_gui = QLabel()
        self.easy_backup = QLabel()
        self.easy_mod = QLabel()
        self.easy_profile = QLabel()
        self.easy_overall = QLabel()
        for w in (self.easy_game, self.easy_gui, self.easy_backup, self.easy_mod, self.easy_profile):
            sl.addWidget(w)
        self.easy_overall.setObjectName("overall")
        sl.addWidget(self.easy_overall)
        lay.addWidget(status)

        actions = QFrame()
        actions.setObjectName("panel")
        row = QHBoxLayout(actions)
        install = QPushButton(self.tr("actions.install_patch"))
        install.clicked.connect(self.install_easy_patch)
        update_compat = QPushButton(self.tr("actions.update_compatibility"))
        update_compat.setToolTip(self.tr("tooltips.update_compatibility"))
        update_compat.clicked.connect(self.install_current_overrides)
        self.easy_install_patch_button = install
        self.easy_update_compat_button = update_compat
        revert = QPushButton(self.tr("actions.revert_patch"))
        revert.clicked.connect(self.revert_easy_patch)
        refresh = QPushButton(self.tr("game.refresh_status"))
        refresh.clicked.connect(self.refresh_all_status)
        start = QPushButton(self.tr("game.start"))
        start.clicked.connect(self.start_game)
        for w in (install, update_compat, revert, refresh):
            row.addWidget(w)
        row.addStretch(1)
        row.addWidget(start)
        lay.addWidget(actions)
        guide = QFrame()
        guide.setObjectName("panel")
        guide_layout = QVBoxLayout(guide)
        guide_layout.setContentsMargins(18, 16, 18, 16)
        guide_layout.setSpacing(8)
        guide_title = QLabel(self.tr("sections.getting_started"))
        guide_title.setObjectName("section")
        guide_layout.addWidget(guide_title)
        guide_text = QLabel(self.tr("guide.html"))
        guide_text.setWordWrap(True)
        guide_text.setObjectName("helpText")
        guide_text.setStyleSheet("color:#e8ebef;")
        guide_layout.addWidget(guide_text)
        lay.addWidget(guide)
        lay.addStretch()
        return page
